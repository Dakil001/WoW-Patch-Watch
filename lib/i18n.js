function normalizeLanguage(value) {
  return String(value || '').toLowerCase().startsWith('en') ? 'en' : 'de';
}

function formatTemplate(template, values = {}) {
  return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, key) => (
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : `{${key}}`
  ));
}

function t(language, key, values = {}) {
  const normalized = normalizeLanguage(language);
  const template = CATALOGS[normalized][key] ?? CATALOGS.de[key] ?? key;
  return formatTemplate(template, values);
}

function getCatalog(language) {
  return { ...CATALOGS[normalizeLanguage(language)] };
}

function localeForLanguage(language) {
  return normalizeLanguage(language) === 'en' ? 'en-GB' : 'de-DE';
}

module.exports = { CATALOGS, normalizeLanguage, t, getCatalog, localeForLanguage };
